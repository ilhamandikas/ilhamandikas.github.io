import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM } from 'jsdom';
import { createMascotPosition } from '../../assets/js/mascot-position.js';
import { createMascotVisibilityMotion } from '../../assets/js/mascot-visibility.js';
import { createMascotSpring } from '../../assets/js/mascot-spring.js';
const markup = fs.readFileSync('layouts/partials/search-mascot.html', 'utf8').replace(/\{\{[^{}]*\}\}/g, '');
const dom = new JSDOM(markup, { pretendToBeVisual: true });
const w = dom.window;
const root = w.document.querySelector('#search-mascot');
const anchor = root.closest('.search-mascot-anchor');
const main = root.querySelector('.search-mascot-main');
const art = root.querySelector('.search-mascot-art');
const pending = [];
function animate(frames, options) {
  let resolve;
  const animation = { frames, options, cancelled: false, finished: new Promise((done) => { resolve = done; }), cancel() { this.cancelled = true; resolve(); }, finish() { resolve(); } };
  pending.push(animation);
  return animation;
}
root.animate = main.animate = art.animate = animate;
const position = createMascotPosition(root);
position.set(123.5, 240);
position.resize(80, 88);
assert.equal(anchor.getAttribute('x'), '123.5');
assert.equal(anchor.getAttribute('width'), '80');
assert.deepEqual(position.get(), { x: 123.5, y: 240 });
assert.equal(main.namespaceURI, 'http://www.w3.org/1999/xhtml', 'controls stay native HTML');
assert.equal(art.namespaceURI, 'http://www.w3.org/2000/svg');
let finishes = 0;
position.dock(400, 300, () => finishes++);
const first = pending.at(-1);
assert.equal(first.options.fill, 'both');
assert(first.options.duration >= 420 && first.options.duration <= 850);
root.getBoundingClientRect = () => ({ left: 250, top: 270, width: 80, height: 88 });
position.stop(true);
assert.deepEqual(position.get(), { x: 250, y: 270 }, 'interruption freezes the actual visual position');
assert(first.cancelled);
await Promise.resolve();
assert.equal(finishes, 0, 'cancelled completion cannot run later');
position.dock(300, 300, () => finishes++);
pending.at(-1).finish(); await Promise.resolve();
assert.equal(finishes, 1);
assert(!root.classList.contains('is-docking'));
assert(pending.at(-1).cancelled, 'finished effect is removed, not persisted');
root.animate = null;
position.dock(300, 300, () => finishes++);
assert.equal(finishes, 2, 'no-animation fallback still completes');
root.animate = animate;
main.getBoundingClientRect = () => ({ left: 250, top: 270, width: root.classList.contains('is-tucked') ? 44 : 96, height: 100 });
art.getBoundingClientRect = () => ({ left: 260, top: 275, width: 72, height: 90 });
let visibilityFinishes = 0;
const visibility = createMascotVisibilityMotion(root, () => visibilityFinishes++);
visibility.run(() => root.classList.add('is-tucked'), false);
assert.equal(root.dataset.visibilityMotion, 'hiding');
const old = pending.slice(-3);
visibility.run(() => root.classList.remove('is-tucked'), false);
assert(old.every((effect) => effect.cancelled));
const current = pending.slice(-3);
current.forEach((effect) => effect.finish());
await Promise.resolve(); await Promise.resolve();
assert.equal(visibilityFinishes, 1);
assert(current.every((effect) => effect.cancelled));
assert(!root.classList.contains('is-transitioning'));
assert.equal(root.dataset.visibilityMotion, undefined);
visibility.run(() => root.classList.add('is-tucked'), true);
assert.equal(visibilityFinishes, 2);
const frames = new Map(); let next = 0, now = 0, reduced = false, dragging = true;
w.requestAnimationFrame = (callback) => { frames.set(++next, callback); return next; };
w.cancelAnimationFrame = (id) => frames.delete(id);
const original = root.querySelector('.search-mascot-wire').getAttribute('d');
const spring = createMascotSpring(root, { reduced: () => reduced, dragging: () => dragging, onFrame() {} });
spring.move(30, 20, 16, now);
for (let i = 0; frames.size && i < 20; i++) {
  const [id, callback] = frames.entries().next().value; frames.delete(id); callback(now += 16);
}
assert(root.querySelector('.search-mascot-spring').getAttribute('transform').startsWith('rotate('));
assert.notEqual(root.querySelector('.search-mascot-wire').getAttribute('d'), original);
dragging = false; spring.release();
for (let i = 0; frames.size && i < 500; i++) {
  const [id, callback] = frames.entries().next().value; frames.delete(id); callback(now += 16);
}
assert.equal(frames.size, 0, 'settled spring stops requesting frames');
assert.equal(root.querySelector('.search-mascot-spring').getAttribute('transform'), null);
assert.equal(root.querySelector('.search-mascot-wire').getAttribute('d'), original);
reduced = true; spring.kick(28); assert.equal(frames.size, 0);
reduced = false; spring.kick(28); assert.equal(frames.size, 1);
spring.reset(); assert.equal(frames.size, 0, 'lifecycle reset cancels the pending frame');
assert.equal(root.querySelectorAll('[style], style').length, 0);
dom.window.close();
console.log('Mascot motion: SVG/HTML namespaces, geometry, interrupted/completed docks, fallback, visibility cancellation/cleanup, SVG springs and idle/reduced-motion frame budget passed.');
