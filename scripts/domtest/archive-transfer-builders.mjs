import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { JSDOM } from 'jsdom';
import { buildTar } from '../../assets/js/tools/tar-command-model.js';
import { buildRsync } from '../../assets/js/tools/rsync-command-model.js';

const tarDefaults = { mode: 'create', archive: 'backup.tar.gz', directory: '/opt/example-app', compression: 'gzip', members: '.', excludes: '', verbose: true, strip: '0', keepOld: true };
const rsDefaults = { mode: 'local', source: '/opt/example-app', destination: '/srv/backups/example-app', contents: true, host: 'backup.example.com', user: 'deploy', port: '22', identity: '', dryRun: true, delete: false, ackDelete: false, compress: false, checksum: false, bandwidth: '', excludes: '' };
const tar = (patch = {}) => buildTar({ ...tarDefaults, ...patch });
const rsync = (patch = {}) => buildRsync({ ...rsDefaults, ...patch });
assert.deepEqual(tar().argv.slice(-2), ['--', '.']);
assert.ok(tar().argv.includes('--force-local'));
for (const compression of ['none', 'gzip', 'bzip2', 'xz', 'zstd']) assert.ok(tar({ compression }).argv.length);
assert.ok(!tar({ mode: 'list', compression: 'invalid', directory: '', members: '' }).argv.includes('--gzip'));
assert.ok(tar({ mode: 'extract' }).argv.includes('--keep-old-files'));
assert.ok(tar({ mode: 'extract' }).previewArgv.includes('--list'));
assert.ok(!tar({ mode: 'extract', keepOld: false }).argv.includes('--keep-old-files'));
for (const patch of [{ mode: 'bad' }, { archive: '-' }, { archive: '~user/archive.tar' }, { archive: 'bad\nname' }, { directory: 'relative' }, { members: '' }, { members: '../secret' }, { members: '/etc' }, { members: '~' }, { compression: 'bad' }, { mode: 'extract', strip: '-1' }, { excludes: 'x\u0000y' }]) assert.throws(() => tar(patch));
assert.ok(rsync().argv.includes('--dry-run'));
assert.deepEqual(rsync().argv.slice(-2), ['/opt/example-app/', '/srv/backups/example-app/']);
assert.equal(rsync({ contents: false }).argv.at(-2), '/opt/example-app');
assert.equal(rsync({ source: '/opt//example-app/./' }).argv.at(-2), '/opt/example-app/');
const upload = rsync({ mode: 'upload', identity: '/home/user/.ssh/id_ed25519', port: '2222' });
assert.ok(upload.argv.includes('-s'));
assert.ok(upload.argv.includes('ssh -p 2222 -i /home/user/.ssh/id_ed25519'));
assert.equal(upload.argv.at(-1), 'deploy@backup.example.com:/srv/backups/example-app/');
assert.equal(rsync({ mode: 'download' }).argv.at(-2), 'deploy@backup.example.com:/opt/example-app/');
const blocked = rsync({ delete: true, dryRun: false });
assert.equal(blocked.argv, null);
assert.ok(blocked.previewArgv.includes('--dry-run'));
assert.ok(rsync({ delete: true, dryRun: false, ackDelete: true }).argv.includes('--delete'));
for (const patch of [{ mode: 'bad' }, { source: '/' }, { source: './', contents: false }, { source: '/same', destination: '/same/' }, { source: '~/app' }, { source: '/data/*' }, { source: '/data/../app' }, { destination: '/', delete: true }, { destination: './', delete: true }, { mode: 'upload', host: 'host;touch bad' }, { mode: 'upload', host: '::1' }, { mode: 'upload', user: '-o' }, { mode: 'upload', port: '65536' }, { mode: 'upload', destination: './relative' }, { mode: 'download', source: './relative' }, { mode: 'upload', identity: '/tmp/key -oProxyCommand=bad' }, { bandwidth: '1;echo bad' }, { excludes: Array(101).fill('*.log').join('\n') }]) assert.throws(() => rsync(patch));

const dir = mkdtempSync(join(tmpdir(), 'ilham-archive-transfer-'));
try {
  const source = join(dir, "source ' $(touch PWNED)");
  const extract = join(dir, 'extracted');
  const destination = join(dir, 'destination');
  for (const path of [source, extract, destination]) mkdirSync(path);
  mkdirSync(join(source, 'node_modules'));
  writeFileSync(join(source, 'data.txt'), 'example data');
  writeFileSync(join(source, 'private.log'), 'excluded example');
  writeFileSync(join(source, 'node_modules', 'ignored.txt'), 'excluded module');
  writeFileSync(join(source, '-I'), 'literal filename, not a tar option');
  const archive = join(dir, 'backup:with space.tar.gz');
  execFileSync('tar', tar({ archive, directory: source, excludes: '*.log\n./node_modules' }).argv);
  const listing = execFileSync('tar', tar({ mode: 'list', archive }).argv, { encoding: 'utf8' });
  assert.ok(listing.includes('data.txt') && !listing.includes('private.log') && !listing.includes('ignored.txt'));
  execFileSync('tar', tar({ mode: 'extract', archive, directory: extract }).argv);
  assert.equal(readFileSync(join(extract, 'data.txt'), 'utf8'), 'example data');
  assert.ok(existsSync(join(extract, '-I')));
  writeFileSync(join(extract, 'data.txt'), 'do not overwrite');
  const conflict = spawnSync('tar', tar({ mode: 'extract', archive, directory: extract }).argv);
  assert.notEqual(conflict.status, 0);
  assert.equal(readFileSync(join(extract, 'data.txt'), 'utf8'), 'do not overwrite');
  const optionArchive = join(dir, 'literal.tar');
  execFileSync('tar', tar({ archive: optionArchive, compression: 'none', directory: source, members: '-I' }).argv);
  assert.ok(execFileSync('tar', ['--list', '--file', optionArchive], { encoding: 'utf8' }).includes('-I'));
  const stripDir = join(dir, 'stripped');
  mkdirSync(stripDir);
  const wrapped = join(dir, 'wrapped.tar');
  execFileSync('tar', tar({ archive: wrapped, compression: 'none', directory: dir, members: 'extracted' }).argv);
  execFileSync('tar', tar({ mode: 'extract', archive: wrapped, directory: stripDir, strip: '1' }).argv);
  assert.ok(existsSync(join(stripDir, 'data.txt')));

  const settings = { source, destination, excludes: '*.log\nnode_modules/' };
  execFileSync('rsync', rsync(settings).argv);
  assert.ok(!existsSync(join(destination, 'data.txt')));
  execFileSync('rsync', rsync({ ...settings, dryRun: false }).argv);
  assert.equal(readFileSync(join(destination, 'data.txt'), 'utf8'), 'example data');
  assert.ok(!existsSync(join(destination, 'private.log')));
  writeFileSync(join(destination, 'obsolete.txt'), 'destination only');
  writeFileSync(join(destination, 'keep.log'), 'excluded destination file');
  execFileSync('rsync', rsync({ ...settings, delete: true }).argv);
  assert.ok(existsSync(join(destination, 'obsolete.txt')));
  execFileSync('rsync', rsync({ ...settings, delete: true, dryRun: false, ackDelete: true }).argv);
  assert.ok(!existsSync(join(destination, 'obsolete.txt')));
  assert.ok(existsSync(join(destination, 'keep.log')));
  const byName = join(dir, 'by-name');
  mkdirSync(byName);
  execFileSync('rsync', rsync({ source, destination: byName, contents: false, dryRun: false }).argv);
  assert.ok(existsSync(join(byName, source.split('/').at(-1), 'data.txt')));

  const body = ['tar-command-builder', 'rsync-command-builder'].map((slug) => readFileSync(new URL(`../../layouts/partials/tools/body/${slug}.html`, import.meta.url), 'utf8')).join('\n');
  const dom = new JSDOM(body, { url: 'https://ilham.dev/tools/tar-command-builder/' });
  globalThis.window = dom.window;
  globalThis.document = dom.window.document;
  const tk = (await import('../../assets/js/toolkit.js')).default;
  await import('../../assets/js/tools/tar-command-builder.js');
  await import('../../assets/js/tools/rsync-command-builder.js');
  const $ = (id) => document.getElementById(id);
  const set = (id, value) => { const el = $(id); if (el.type === 'checkbox') el.checked = value; else el.value = value; el.dispatchEvent(new window.Event('change')); };
  assert.match($('tar-output').value, /tar --create/);
  set('tar-mode', 'extract');
  assert.match($('tar-output').value, /--directory .\/restore/);
  assert.equal($('tar-preview-panel').hidden, false);
  set('tar-archive', '-');
  assert.equal($('tar-output').value, '');
  assert.equal($('tar-copy').disabled, true);
  set('tar-mode', 'create');
  set('tar-archive', join(dir, 'shell quoted.tar.gz'));
  set('tar-sourceDirectory', source);
  const shellCommand = $('tar-output').value;
  execFileSync('sh', ['-c', shellCommand], { cwd: dir });
  assert.ok(!existsSync(join(dir, 'PWNED')));
  set('rs-source', source);
  set('rs-destination', join(dir, "shell destination ' $(touch PWNED)"));
  set('rs-dryRun', false);
  execFileSync('sh', ['-c', $('rs-output').value], { cwd: dir });
  assert.ok(!existsSync(join(dir, 'PWNED')));
  assert.ok(existsSync(join(dir, "shell destination ' $(touch PWNED)", 'data.txt')));
  set('rs-delete', true);
  assert.equal($('rs-output').value, '');
  assert.equal($('rs-copy').disabled, true);
  assert.ok($('rs-preview').value.includes('--dry-run'));
  set('rs-ackDelete', true);
  assert.ok($('rs-output').value.includes('--delete'));
  set('rs-compress', true);
  assert.equal($('rs-ackDelete').checked, false);
  assert.equal($('rs-output').value, '');
  set('rs-dryRun', true);
  assert.ok($('rs-output').value.includes('--dry-run'));
  assert.equal(document.querySelectorAll('input:not([data-no-memory]), select:not([data-no-memory]), textarea:not([data-no-memory])').length, 0);
  assert.ok(tk.shq("a'b").includes("\\'"));
  dom.window.close();
} finally { rmSync(dir, { recursive: true, force: true }); }
console.log('tar/rsync builders: native round trips, excludes, dry-run, deletion guards, shell quoting, and DOM tests passed');
