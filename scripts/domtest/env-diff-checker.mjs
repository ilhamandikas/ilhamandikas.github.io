import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { parseEnv, compareEnv } from '../../assets/js/tools/env-diff-parser.js';

const parse = (s) => parseEnv(s, 'Left');
assert.deepEqual([...parse('\uFEFF# comment\r\nexport A="hello # world" # note\rB=\rC=abc#comment')], [['A', 'hello # world'], ['B', ''], ['C', 'abc']]);
assert.equal(parse('A=" spaced "').get('A'), ' spaced ');
assert.equal(parse('A="a\\n${HOST}"').get('A'), 'a\\n${HOST}');
assert.equal(parse('A="a\\\"b"').get('A'), 'a\\\"b');
assert.deepEqual(compareEnv(parse('A=1\nB=\nC=3'), parse('A="1"\nB=2\nD=4')).map((r) => r.kind), ['Same', 'Changed', 'Only left', 'Only right']);
assert.equal(compareEnv(parse(''), parse('A=')).at(0).kind, 'Only right');
assert.equal(compareEnv(parse('a=1'), parse('A=1')).length, 2);
assert.equal(parse('__proto__=literal').get('__proto__'), 'literal');
for (const bad of ['A=1\nA=2', 'BAD KEY=x', 'A="unterminated', 'A="x" trailing', 'A="first\nsecond"', 'echo secret', 'A=can\'t']) {
  assert.throws(() => parse(bad), /Left, line \d+:/);
}
assert.throws(() => parse('A=' + 'x'.repeat(1000000)), /maximum input size/);
assert.equal(parse('A=' + 'x'.repeat(999998)).get('A').length, 999998);
assert.equal(compareEnv(parse(''), parse('')).length, 0);
assert.equal(compareEnv(parse(Array.from({ length: 10000 }, (_, i) => `KEY_${i}=${i}`).join('\n')), new Map()).length, 10000);

const html = readFileSync(new URL('../../layouts/partials/tools/body/env-diff-checker.html', import.meta.url), 'utf8');
const dom = new JSDOM(html, { url: 'https://ilham.dev/tools/env-diff-checker/' });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
window.tk = { setStatus(el, text) { el.textContent = text; } };
window.confirm = () => true;
await import('../../assets/js/tools/env-diff-checker.js');
const $ = (id) => document.getElementById(`ed-${id}`);
const change = (id) => $(id).dispatchEvent(new window.Event('change'));
$('example').click();
assert.match($('status').textContent, /1 only left.*1 only right.*2 changed.*1 unchanged/);
assert.ok(!$('table').textContent.includes('example-only'));
assert.ok(!$('report').value.includes('example-only'));
$('reveal').checked = true;
change('reveal');
assert.ok($('table').textContent.includes('example-only'));
assert.ok(!$('report').value.includes('example-only'));
$('same').checked = true;
change('same');
assert.equal($('results').children.length, 5);
$('left').value = 'A=<img src=x onerror=alert(1)>';
$('right').value = 'A=different';
$('run').click();
$('reveal').checked = true;
change('reveal');
assert.equal($('results').querySelector('img'), null);
assert.ok($('table').textContent.includes('<img'));
$('left').dispatchEvent(new window.Event('input'));
assert.equal($('results').children.length, 0);
assert.equal($('reveal').checked, false);
assert.equal($('copy').disabled, true);
$('left').value = 'A=very-secret\nA=other-secret';
$('run').click();
assert.match($('status').textContent, /Duplicate key/);
assert.ok(!$('status').textContent.includes('secret'));
assert.ok($('left').value.includes('very-secret'));
$('clear').click();
assert.equal($('left').value + $('right').value + $('report').value, '');
assert.equal($('table').hidden, true);
assert.equal(document.querySelectorAll('input:not([data-no-memory]), textarea:not([data-no-memory])').length, 0);
dom.window.close();
console.log('env-diff-checker: parser and DOM tests passed');
