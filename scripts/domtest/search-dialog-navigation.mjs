import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { initSearchDialogNavigation } from '../../assets/js/search-dialog-navigation.js';

const dom = new JSDOM('<div id="dialog"><input type="search"><button>Close</button><div class="global-search-results"><a href="/one/">One</a><a href="/two/">Two</a><a href="/three/">Three</a></div></div>');
globalThis.document = dom.window.document;
const dialog = document.querySelector('#dialog');
const input = dialog.querySelector('input');
const results = dialog.querySelector('.global-search-results');
const links = [...results.querySelectorAll('a')];
let closed = 0;
let clicked = null;
links.forEach((link) => link.addEventListener('click', (event) => { event.preventDefault(); clicked = link; }));
initSearchDialogNavigation(dialog, { close: () => { closed++; dialog.hidden = true; } });
const key = (name, extra = {}) => document.activeElement.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: name, bubbles: true, cancelable: true, ...extra }));
input.focus(); key('ArrowDown'); assert.equal(document.activeElement, links[0]);
key('ArrowDown'); assert.equal(document.activeElement, links[1]);
key('ArrowUp'); assert.equal(document.activeElement, links[0]);
key('ArrowUp'); assert.equal(document.activeElement, input);
key('ArrowUp'); assert.equal(document.activeElement, links[2]);
key('ArrowDown'); assert.equal(document.activeElement, links[0], 'down wraps from last result');
input.focus(); key('Enter'); assert.equal(clicked, links[0]);
clicked = null; key('Enter', { isComposing: true }); assert.equal(clicked, null, 'IME confirmation is not navigation');
key('ArrowDown', { ctrlKey: true }); assert.equal(document.activeElement, input);
key('Tab', { shiftKey: true }); assert.equal(document.activeElement, links[2], 'Shift+Tab stays in the modal');
key('Tab'); assert.equal(document.activeElement, input, 'Tab wraps to search');
links[1].focus(); key('Escape'); assert.equal(closed, 1, 'Escape also works from a result');
dialog.hidden = false; results.replaceChildren(); input.focus();
key('ArrowDown'); key('ArrowUp'); key('Enter'); assert.equal(clicked, null, 'empty results are safe');
key('Tab', { shiftKey: true }); assert.equal(document.activeElement, dialog.querySelector('button'));
key('Tab'); assert.equal(document.activeElement, input);
dom.window.close();
console.log('Search dialog: arrows, Enter, IME, modifiers, empty results, Tab trap and Escape passed.');
