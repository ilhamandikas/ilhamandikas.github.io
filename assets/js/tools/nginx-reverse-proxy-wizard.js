// nginx reverse proxy wizard: answer a few questions, get a server block.
const { tk } = window;

const els = {
  names: document.querySelector('#nrp-names'),
  www: document.querySelector('#nrp-www'),
  target: document.querySelector('#nrp-target'),
  extra: document.querySelector('#nrp-extra'),
  balance: document.querySelector('#nrp-balance'),
  keepalive: document.querySelector('#nrp-keepalive'),
  tls: document.querySelector('#nrp-tls'),
  cert: document.querySelector('#nrp-cert'),
  key: document.querySelector('#nrp-key'),
  hsts: document.querySelector('#nrp-hsts'),
  websocket: document.querySelector('#nrp-websocket'),
  stream: document.querySelector('#nrp-stream'),
  headers: document.querySelector('#nrp-headers'),
  tokens: document.querySelector('#nrp-tokens'),
  logs: document.querySelector('#nrp-logs'),
  body: document.querySelector('#nrp-body'),
  timeout: document.querySelector('#nrp-timeout'),
  out: document.querySelector('#nrp-out'),
  meta: document.querySelector('#nrp-meta'),
  notes: document.querySelector('#nrp-notes'),
  status: document.querySelector('#nrp-status'),
  tlsRow: document.querySelector('#nrp-tls-row'),
  hstsCard: document.querySelector('#nrp-hsts-card'),
  prev: document.querySelector('#nrp-prev'),
  next: document.querySelector('#nrp-next'),
};

const TOTAL_STEPS = 4;
let step = 1;

const indented = (lines, pad = '    ') =>
  lines
    .filter((line) => line !== null)
    .flatMap((line) => String(line).split('\n'))
    .map((line) => (line === '' ? '' : pad + line));

const NAME = /^(\*\.)?[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)*$|^_$|^\d{1,3}(\.\d{1,3}){3}$/;

const upstreamName = (names) => {
  const base = (names[0] || 'app').replace(/^\*\./, '').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '');
  return `${base || 'app'}-upstream`;
};

function settings() {
  return {
    names: els.names.value.split(/[\s,]+/).filter(Boolean),
    www: els.www.value,
    target: els.target.value.trim() || 'http://127.0.0.1:3000',
    extra: els.extra.value.split(/\r?\n/).map((line) => line.trim()).filter(Boolean),
    balance: els.balance.value,
    keepalive: Math.max(0, Number(els.keepalive.value) || 0),
    tls: els.tls.checked,
    cert: els.cert.value.trim() || '/etc/letsencrypt/live/app.example.com/fullchain.pem',
    key: els.key.value.trim() || '/etc/letsencrypt/live/app.example.com/privkey.pem',
    hsts: els.hsts.checked,
    websocket: els.websocket.checked,
    stream: els.stream.checked,
    headers: els.headers.checked,
    tokens: els.tokens.checked,
    logs: els.logs.checked,
    body: Math.max(1, Number(els.body.value) || 32),
    timeout: Math.max(1, Number(els.timeout.value) || 60),
  };
}

function redirectPairs(s) {
  if (s.www === 'to-apex') return s.names.filter((n) => n.startsWith('www.')).map((n) => [n, n.slice(4)]);
  if (s.www === 'to-www') return s.names.filter((n) => !n.startsWith('www.') && n.includes('.')).map((n) => [n, `www.${n}`]);
  return [];
}

function securityHeaders(s) {
  const lines = [
    'add_header X-Content-Type-Options "nosniff" always;',
    'add_header Referrer-Policy "strict-origin-when-cross-origin" always;',
    'add_header X-Frame-Options "SAMEORIGIN" always;',
  ];
  if (s.tls && s.hsts) lines.push('add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;');
  return lines;
}

function generate(s) {
  const out = [];
  const url = new URL(s.target);
  const secure = url.protocol === 'https:';
  const upstream = upstreamName(s.names);
  const pairs = redirectPairs(s);
  const bounced = new Set(pairs.map(([from]) => from));
  const mainNames = s.names.filter((n) => !bounced.has(n));
  const main = mainNames.length ? mainNames.join(' ') : s.names.join(' ');

  out.push(
    `# ${s.names.join(' ') || 'reverse proxy'}`,
    '#',
    '# Generated by https://ilham.dev/tools/nginx-reverse-proxy-wizard/',
    '# Check it before you rely on it:  nginx -t && systemctl reload nginx',
    '',
  );

  const pool = [url.host, ...s.extra];
  out.push(`upstream ${upstream} {`);
  if (s.balance !== 'round-robin') out.push(...indented([`${s.balance};`]));
  out.push(...indented(pool.map((host) => `server ${host};`)));
  if (s.keepalive > 0 && !secure) out.push(...indented([`keepalive ${s.keepalive};`]));
  out.push('}');
  if (secure && s.keepalive > 0) {
    out.push('', '# keepalive is skipped because the target is https; nginx cannot reuse those connections the same way.');
  }

  if (s.websocket) {
    out.push(
      '',
      'map $http_upgrade $connection_upgrade {',
      ...indented(['default upgrade;', "''      close;"]),
      '}',
    );
  }

  for (const [from, to] of pairs) {
    out.push('', 'server {', ...indented([
      'listen 80;',
      'listen [::]:80;',
      `server_name ${from};`,
      `return 301 $scheme://${to}$request_uri;`,
    ]), '}');
    if (s.tls) {
      out.push('', 'server {', ...indented([
        'listen 443 ssl;',
        'listen [::]:443 ssl;',
        'http2 on;',
        `server_name ${from};`,
        `ssl_certificate     ${s.cert};`,
        `ssl_certificate_key ${s.key};`,
        `return 301 $scheme://${to}$request_uri;`,
      ]), '}');
    }
  }

  if (s.tls) {
    out.push('', 'server {', ...indented([
      'listen 80;',
      'listen [::]:80;',
      `server_name ${main};`,
      'location /.well-known/acme-challenge/ { root /var/www/html; }',
      'location / { return 301 https://$host$request_uri; }',
    ]), '}');
  }

  const server = [];
  server.push(...(s.tls ? ['listen 443 ssl;', 'listen [::]:443 ssl;', 'http2 on;'] : ['listen 80;', 'listen [::]:80;']));
  server.push(`server_name ${main};`, '');
  if (s.tokens) server.push('server_tokens off;', '');
  if (s.tls) {
    server.push(
      `ssl_certificate     ${s.cert};`,
      `ssl_certificate_key ${s.key};`,
      'ssl_protocols TLSv1.2 TLSv1.3;',
      'ssl_prefer_server_ciphers off;',
      'ssl_session_cache shared:SSL:10m;',
      'ssl_session_timeout 1d;',
      '',
    );
  }
  server.push(`client_max_body_size ${s.body}m;`, '');
  if (s.logs) {
    const label = (s.names[0] || 'app').replace(/^\*\./, '').replace(/[^a-z0-9.-]/gi, '-');
    server.push(`access_log /var/log/nginx/${label}.access.log;`, `error_log  /var/log/nginx/${label}.error.log warn;`, '');
  }
  if (s.headers) server.push(...securityHeaders(s), '');

  const location = [
    `proxy_pass ${secure ? 'https' : 'http'}://${upstream};`,
    'proxy_http_version 1.1;',
    'proxy_set_header Host $host;',
    'proxy_set_header X-Real-IP $remote_addr;',
    'proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
    'proxy_set_header X-Forwarded-Proto $scheme;',
    'proxy_set_header X-Forwarded-Host $host;',
  ];
  if (s.websocket) location.push('proxy_set_header Upgrade $http_upgrade;', 'proxy_set_header Connection $connection_upgrade;');
  if (s.stream) location.push('proxy_buffering off;');
  location.push(`proxy_read_timeout ${s.timeout}s;`);
  server.push('location / {', ...indented(location), '}', '');
  server.push('location ~ /\\. { deny all; }', '');

  out.push('', 'server {', ...indented(server), '}');
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

function notesFor(s) {
  const notes = [];
  if (s.websocket) notes.push('The Upgrade/Connection headers use the $connection_upgrade map above; without it nginx cannot choose between upgrade and close.');
  if (s.stream) notes.push('Buffering is off, which suits SSE and long-lived streams but lets a slow client hold a worker for longer.');
  if (!s.tls) notes.push('Plain HTTP only — right behind a load balancer that terminates TLS, wrong on the open internet.');
  if (s.extra.length) notes.push('Extra upstream servers are pooled; make sure they all serve the same app, or sessions will jump between them.');
  notes.push('http2 on; needs nginx 1.25.1 or newer; on older versions use listen 443 ssl http2; instead.');
  return notes.join(' ');
}

function render() {
  els.tlsRow.hidden = !els.tls.checked;
  els.hstsCard.hidden = !els.tls.checked;
  const s = settings();
  let text = '';
  let problem = '';
  try {
    if (!s.names.length) problem = 'Add a domain to start';
    else if (!/^https?:\/\/[^\s/]+/.test(s.target)) problem = 'The upstream target needs to look like http://127.0.0.1:3000';
    else text = generate(s);
  } catch {
    problem = 'The upstream target is not a valid URL';
  }
  const bad = s.names.filter((n) => !NAME.test(n));
  if (!problem && bad.length) problem = `Not a valid server name: ${bad.join(', ')}`;
  els.out.value = problem ? '' : text;
  els.meta.textContent = text ? `${s.names.length} name${s.names.length === 1 ? '' : 's'} · ${s.tls ? 'HTTPS' : 'HTTP'} · ${s.websocket ? 'websocket' : 'http'}` : '';
  els.notes.textContent = text ? notesFor(s) : '';
  tk.setStatus(els.status, problem || '');
}

function showStep(target) {
  step = Math.min(TOTAL_STEPS, Math.max(1, target));
  document.querySelectorAll('.nrp-step').forEach((section) => { section.hidden = Number(section.dataset.step) !== step; });
  document.querySelectorAll('.nrp-step-btn').forEach((button) => button.classList.toggle('is-active', Number(button.dataset.step) === step));
  els.prev.disabled = step === 1;
  els.next.disabled = step === TOTAL_STEPS;
}

els.prev.addEventListener('click', () => showStep(step - 1));
els.next.addEventListener('click', () => showStep(step + 1));
document.querySelectorAll('.nrp-step-btn').forEach((button) => {
  button.addEventListener('click', () => showStep(Number(button.dataset.step)));
});

tk.live([
  els.names, els.www, els.target, els.extra, els.balance, els.keepalive, els.tls, els.cert, els.key,
  els.hsts, els.websocket, els.stream, els.headers, els.tokens, els.logs, els.body, els.timeout,
], render);
showStep(1);
